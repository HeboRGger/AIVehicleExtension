--
-- mogliHud.lua — Adapted for Farming Simulator 25 (FS25)
-- Preserves the exact mogliHud.newClass("AIVEHud", "atHud") factory API used by AIVehicleExtension,
-- replaces removed "dataS/menu/blank.png" with bundled "dds/panelFill.dds", wraps Overlay calls in pcall,
-- and supports 1-row compact and 2-row expanded FS25 HUD settings mode.
--

local mogliHudVersion = 2.52
local mogliHudClass   = g_currentModName .. ".mogliHud"

local defaultButtonWidth  = 0.027
local defaultHeightFactor = 0.875
local defaultBorderFactor = 0.15
local defaultTextFactor   = 0.45

local function getNoNil(val, defaultVal)
	if val == nil then
		return defaultVal
	end
	return val
end

local function createSafeOverlay(filename, x, y, width, height)
	if Overlay == nil or Overlay.new == nil then
		return nil
	end
	local ok, ov = pcall(Overlay.new, filename, x, y, width, height)
	if ok and ov ~= nil then
		return ov
	end
	return nil
end

local function safeOverlayRender(ov, x, y, w, h)
	if ov == nil then
		return
	end
	if x ~= nil and y ~= nil and ov.setPosition ~= nil then
		pcall(ov.setPosition, ov, x, y)
	end
	if w ~= nil and h ~= nil and ov.setDimension ~= nil then
		pcall(ov.setDimension, ov, w, h)
	end
	if ov.render ~= nil then
		pcall(ov.render, ov)
	end
end

local function safeOverlaySetColor(ov, r, g, b, a)
	if ov ~= nil and ov.setColor ~= nil then
		pcall(ov.setColor, ov, r, g, b, a)
	end
end

local function safeOverlayDelete(ov)
	if ov ~= nil and ov.delete ~= nil then
		pcall(ov.delete, ov)
	end
end

if _G[mogliHudClass] ~= nil and _G[mogliHudClass].version ~= nil and _G[mogliHudClass].version >= mogliHudVersion then
	print("Factory class " .. tostring(mogliHudClass) .. " already exists in version " .. tostring(_G[mogliHudClass].version))
else
	_G[mogliHudClass] = {}
	_G[mogliHudClass].version = mogliHudVersion

	--=======================================================================================
	-- mogliHud.newClass
	--=======================================================================================
	local function newClass(_globalClassName_, _level0_)
		if _G[_globalClassName_] ~= nil and _G[_globalClassName_].factoryVersion ~= nil and _G[_globalClassName_].factoryClassName ~= nil and _G[_globalClassName_].factoryVersion >= mogliHudVersion then
			print(tostring(_globalClassName_) .. " was already generated by factory " .. tostring(_G[_globalClassName_].factoryClassName) .. " with version " .. tostring(_G[_globalClassName_].factoryVersion))
			return
		end

		local _newClass_ = {}
		_newClass_.factoryClassName = mogliHudClass
		_newClass_.factoryVersion   = mogliHudVersion

		if _level0_ == nil then
			_level0_ = "mogliHud_" .. tostring(_globalClassName_)
		end

		------------------------------------------------------------------------
		-- helper functions
		------------------------------------------------------------------------
		function _newClass_.bool2int(boolean)
			if boolean then
				return 1
			end
			return 0
		end

		function _newClass_.printCallstack()
			if printCallstack ~= nil then
				printCallstack()
			end
		end

		function _newClass_.getText(id)
			if id == nil then
				return "nil"
			end
			if g_i18n ~= nil and g_i18n:hasText(id) then
				return g_i18n:getText(id)
			end
			return id
		end

		function _newClass_.getXmlBool(xmlFile, key, default)
			local l = getXMLBool(xmlFile, key)
			if l ~= nil then
				return l
			end
			return default
		end

		function _newClass_.getXmlFloat(xmlFile, key, default)
			local f = getXMLFloat(xmlFile, key)
			if f ~= nil then
				return f
			end
			return default
		end

		function _newClass_.getXmlInt(xmlFile, key, default)
			local f = getXMLInt(xmlFile, key)
			if f ~= nil then
				return f
			end
			return default
		end

		------------------------------------------------------------------------
		-- init
		------------------------------------------------------------------------
		function _newClass_:init(directory, hudName, hudBackground, onTextID, offTextID, showHudKey, x, y, nx, ny, cbOnClick, width, height, text, border, smallNx, smallNy)
			self[_level0_] = {}
			self[_level0_].Directory = directory

			local screenRatio = (g_screenWidth ~= nil and g_screenHeight ~= nil and g_screenHeight > 0) and (g_screenWidth / g_screenHeight) or (16 / 9)
			self[_level0_].BtnWidth  = getNoNil(width,  defaultButtonWidth)
			self[_level0_].BtnHeight = getNoNil(height, defaultHeightFactor * self[_level0_].BtnWidth * screenRatio)
			self[_level0_].Border    = getNoNil(border, defaultBorderFactor * self[_level0_].BtnHeight)
			self[_level0_].TextSize  = getNoNil(text,   defaultTextFactor   * self[_level0_].BtnHeight)
			self[_level0_].Nx        = nx
			self[_level0_].Ny        = ny
			self[_level0_].Width     = nx * (self[_level0_].BtnWidth + self[_level0_].Border) + self[_level0_].Border
			self[_level0_].Height    = ny * (self[_level0_].BtnHeight + self[_level0_].Border) + 2 * self[_level0_].Border + self[_level0_].TextSize + math.max(0.5 * self[_level0_].BtnHeight, self[_level0_].TextSize)
			self[_level0_].PosX      = x
			self[_level0_].PosY      = y
			self[_level0_].TextPosY  = y + 0.5 * self[_level0_].Border
			self[_level0_].TextPosX  = x + 0.5 * self[_level0_].Border
			self[_level0_].BtnPosX   = self[_level0_].TextPosX
			self[_level0_].BtnPosY   = self[_level0_].TextPosY + self[_level0_].Border + self[_level0_].TextSize + (ny - 1) * (self[_level0_].BtnHeight + self[_level0_].Border)
			self[_level0_].TextPosY  = self[_level0_].TextPosY + 0.25 * self[_level0_].TextSize

			local blankTexPath = Utils.getFilename("dds/panelFill.dds", self[_level0_].Directory)
			if type(hudBackground) == "string" then
				self[_level0_].Path    = Utils.getFilename(hudBackground, self[_level0_].Directory)
				self[_level0_].Overlay = createSafeOverlay(self[_level0_].Path, self[_level0_].PosX, self[_level0_].PosY, self[_level0_].Width, self[_level0_].Height)
			else
				local bg = 0.85
				if type(hudBackground) == "number" then
					bg = math.max(hudBackground, 0.78)
				end
				self[_level0_].Overlay = createSafeOverlay(blankTexPath, self[_level0_].PosX, self[_level0_].PosY, self[_level0_].Width, self[_level0_].Height)
				safeOverlaySetColor(self[_level0_].Overlay, 0.035, 0.035, 0.035, math.max(bg,0.95))
			end
			self[_level0_].Accent = createSafeOverlay(blankTexPath, x, y + self[_level0_].Height - 0.002, self[_level0_].Width, 0.002)
			safeOverlaySetColor(self[_level0_].Accent, 0.35, 0.65, 0.10, 1)

			self[_level0_].GuiActive    = false
			self[_level0_].GuiShowKey   = showHudKey
			self[_level0_].GuiOnTextID  = onTextID
			self[_level0_].GuiOffTextID = offTextID
			self[_level0_].CBOnClick    = cbOnClick
			self[_level0_].Status       = 0
			self[_level0_].Title        = ""

			_newClass_.addCloseButton(self, nx, ny)

			if smallNx ~= nil and smallNy ~= nil and (smallNx < nx or smallNy < ny) then
				_newClass_.addResizeButton(self, nx, ny)
				self[_level0_].ResizeSmall  = false
				self[_level0_].SmallWidth   = smallNx * (self[_level0_].BtnWidth + self[_level0_].Border) + self[_level0_].Border
				self[_level0_].SmallHeight  = smallNy * (self[_level0_].BtnHeight + self[_level0_].Border) + 2 * self[_level0_].Border + self[_level0_].TextSize + math.max(0.5 * self[_level0_].BtnHeight, self[_level0_].TextSize)
				self[_level0_].SmallBtnPosY = self[_level0_].TextPosY - 0.25 * self[_level0_].TextSize + self[_level0_].Border + self[_level0_].TextSize + (smallNy - 1) * (self[_level0_].BtnHeight + self[_level0_].Border)
			else
				self[_level0_].ResizeSmall  = false
				self[_level0_].SmallWidth   = self[_level0_].Width
				self[_level0_].SmallHeight  = self[_level0_].Height
				self[_level0_].SmallBtnPosY = self[_level0_].BtnPosY
			end
		end

		------------------------------------------------------------------------
		-- addButton
		------------------------------------------------------------------------
		function _newClass_:addButton(imgEnabled, imgDisabled, cbOnClick, cbVisible, nx, ny, textEnabled, textDisabled, textCallback, imgCallback, smallNx, smallNy)
			local x = self[_level0_].BtnPosX + (nx - 1) * (self[_level0_].BtnWidth + self[_level0_].Border)
			local y = self[_level0_].BtnPosY - (ny - 1) * (self[_level0_].BtnHeight + self[_level0_].Border)
			local img1 = getNoNil(imgEnabled, "empty.dds")
			local state, result = pcall(Utils.getFilename, img1, self[_level0_].Directory)
			if not state then
				if AIVELogger ~= nil then
					AIVELogger.error("HUD", "%s (img1: %s)", tostring(result), tostring(img1))
				end
				return
			end
			local overlay = createSafeOverlay(result, x, y, self[_level0_].BtnWidth, self[_level0_].BtnHeight)
			local img2 = "empty.dds"
			if imgDisabled ~= nil then
				img2 = imgDisabled
			end
			local overlay2 = overlay
			if img2 ~= img1 then
				state, result = pcall(Utils.getFilename, img2, self[_level0_].Directory)
				if not state then
					if AIVELogger ~= nil then
						AIVELogger.error("HUD", "%s (img2: %s)", tostring(result), tostring(img2))
					end
					return
				end
				overlay2 = createSafeOverlay(result, x, y, self[_level0_].BtnWidth, self[_level0_].BtnHeight)
			end
			local button = {
				nx         = nx,
				ny         = ny,
				enabled    = true,
				ovEnabled  = overlay,
				ovDisabled = overlay2,
				onClick    = cbOnClick,
				onVisible  = cbVisible,
				twoState   = (imgDisabled ~= nil),
				rect       = { x, y, x + self[_level0_].BtnWidth, y + self[_level0_].BtnHeight },
				text1      = textEnabled,
				text2      = textDisabled,
				textcb     = textCallback,
				onRender   = imgCallback
			}
			button.overlays = {}
			button.overlays[img1] = overlay
			if img2 ~= img1 then
				button.overlays[img2] = overlay2
			end
			if self[_level0_].Buttons == nil then
				self[_level0_].Buttons = {}
			end
			table.insert(self[_level0_].Buttons, button)
			return button
		end

		------------------------------------------------------------------------
		-- onClose
		------------------------------------------------------------------------
		function _newClass_:onClose()
			_newClass_.showGui(self, false)
		end

		------------------------------------------------------------------------
		-- addCloseButton
		------------------------------------------------------------------------
		function _newClass_:addCloseButton(nx, ny)
			local x = self[_level0_].BtnPosX + (nx - 1) * (self[_level0_].BtnWidth + self[_level0_].Border) + 0.5 * self[_level0_].BtnWidth
			local y = self[_level0_].BtnPosY + self[_level0_].BtnHeight + self[_level0_].Border
			local overlay = createSafeOverlay(Utils.getFilename("close.dds", self[_level0_].Directory), x, y, 0.5 * self[_level0_].BtnWidth, 0.5 * self[_level0_].BtnHeight)
			local button = {
				isHeader   = true,
				enabled    = true,
				ovEnabled  = overlay,
				ovDisabled = nil,
				onClick    = _newClass_.onClose,
				onVisible  = nil,
				twoState   = false,
				rect       = { x, y, x + 0.5 * self[_level0_].BtnWidth, y + 0.5 * self[_level0_].BtnHeight },
				text1      = nil,
				text2      = nil,
				textcb     = nil,
				onRender   = nil
			}
			button.overlays = {}
			button.overlays["close.dds"] = overlay
			if self[_level0_].Buttons == nil then
				self[_level0_].Buttons = {}
			end
			table.insert(self[_level0_].Buttons, button)
			return button
		end

		------------------------------------------------------------------------
		-- onResize
		------------------------------------------------------------------------
		function _newClass_:onResize()
			self[_level0_].ResizeSmall = not self[_level0_].ResizeSmall
		end

		------------------------------------------------------------------------
		-- addResizeButton
		------------------------------------------------------------------------
		function _newClass_:addResizeButton(nx, ny)
			local x = self[_level0_].BtnPosX + (nx - 1) * (self[_level0_].BtnWidth + self[_level0_].Border)
			local y = self[_level0_].BtnPosY + self[_level0_].BtnHeight + self[_level0_].Border
			local overlay = createSafeOverlay(Utils.getFilename("resize.dds", self[_level0_].Directory), x, y, 0.5 * self[_level0_].BtnWidth, 0.5 * self[_level0_].BtnHeight)
			local button = {
				isHeader   = true,
				enabled    = true,
				ovEnabled  = overlay,
				ovDisabled = nil,
				onClick    = _newClass_.onResize,
				onVisible  = nil,
				twoState   = false,
				rect       = { x, y, x + 0.5 * self[_level0_].BtnWidth, y + 0.5 * self[_level0_].BtnHeight },
				text1      = nil,
				text2      = nil,
				textcb     = nil,
				onRender   = nil
			}
			button.overlays = {}
			button.overlays["resize.dds"] = overlay
			if self[_level0_].Buttons == nil then
				self[_level0_].Buttons = {}
			end
			table.insert(self[_level0_].Buttons, button)
			return button
		end

		------------------------------------------------------------------------
		-- setStatus
		------------------------------------------------------------------------
		function _newClass_:setStatus(status)
			if self[_level0_] == nil then
			elseif status == nil or status == 0 then
				self[_level0_].Status = 0
			else
				self[_level0_].Status = status
			end
		end

		------------------------------------------------------------------------
		-- setTitle
		------------------------------------------------------------------------
		function _newClass_:setTitle(title)
			if self[_level0_] == nil then
			elseif title == nil then
				self[_level0_].Title = ""
			else
				self[_level0_].Title = _newClass_.getText(title)
			end
		end

		------------------------------------------------------------------------
		-- getInfoText
		------------------------------------------------------------------------
		function _newClass_:getInfoText()
			if self[_level0_] == nil or self[_level0_].InfoText == nil then
				return ""
			end
			return self[_level0_].InfoText
		end

		------------------------------------------------------------------------
		-- setInfoText
		------------------------------------------------------------------------
		function _newClass_:setInfoText(infoText)
			if self[_level0_] == nil then
			elseif infoText == nil then
				self[_level0_].InfoText = nil
			else
				self[_level0_].InfoText = infoText
			end
		end

		------------------------------------------------------------------------
		-- setInfoTextID
		------------------------------------------------------------------------
		function _newClass_:setInfoTextID(infoTextID)
			if self[_level0_] == nil then
			elseif infoTextID == nil then
				self[_level0_].InfoText = nil
			else
				self[_level0_].InfoText = _newClass_.getText(infoTextID)
			end
		end

		------------------------------------------------------------------------
		-- mouseEvent
		------------------------------------------------------------------------
		function _newClass_:mouseEvent(posX, posY, isDown, isUp, button)
			if self[_level0_] == nil then
				return
			end
			self[_level0_].Tooltip = nil
			self[_level0_].DynamicTooltip = nil
			local textID, textCB
			if self[_level0_].GuiActive and self[_level0_].Buttons ~= nil then
				local isSmall = self[_level0_].ResizeSmall
				for _, overlayButton in pairs(self[_level0_].Buttons) do
					local visibleRow = overlayButton.isHeader or not isSmall or overlayButton.ny == nil or overlayButton.ny <= 1
					if visibleRow and overlayButton.rect[1] <= posX and posX <= overlayButton.rect[3] and overlayButton.rect[2] <= posY and posY <= overlayButton.rect[4] then
						if overlayButton.onClick ~= nil and isDown and button == 1 then
							if overlayButton.enabled then
								if overlayButton.twoState ~= nil then
									overlayButton.onClick(self, true)
								else
									overlayButton.onClick(self)
								end
								if type(self[_level0_].CBOnClick) == "function" then
									self[_level0_].CBOnClick(self)
								end
							elseif overlayButton.twoState then
								overlayButton.onClick(self, false)
								if type(self[_level0_].CBOnClick) == "function" then
									self[_level0_].CBOnClick(self)
								end
							end
						end
						if overlayButton.text1 ~= nil
								and (overlayButton.enabled
									or not overlayButton.twoState
									or overlayButton.text2 == nil) then
							textID = overlayButton.text1
						elseif overlayButton.text2 ~= nil then
							textID = overlayButton.text2
						end
						textCB = overlayButton.textcb
						if overlayButton.dynamicTooltip then self[_level0_].DynamicTooltip=overlayButton end
						break
					end
				end
			end

			if textID ~= nil then
				self[_level0_].Tooltip = _newClass_.getText(textID)
				if textCB ~= nil then
					self[_level0_].Tooltip = textCB(self, self[_level0_].Tooltip)
				end
			end
		end

		------------------------------------------------------------------------
		-- renderButtons
		------------------------------------------------------------------------
		function _newClass_:renderButtons()
			if self[_level0_].Buttons == nil then
				return
			end
			local isSmall = self[_level0_].ResizeSmall
			for _, button in pairs(self[_level0_].Buttons) do
				local visibleRow = button.isHeader or not isSmall or button.ny == nil or button.ny <= 1
				if visibleRow then
					if button.onVisible ~= nil then
						button.enabled = button.onVisible(self)
					end
					local img = nil
					if button.onRender ~= nil then
						img = button.onRender(self)
					end
					if img ~= nil and img ~= "" then
						if button.overlays == nil then
							button.overlays = {}
						end
						local ov
						if button.overlays[img] == nil then
							ov = createSafeOverlay(Utils.getFilename(img, self[_level0_].Directory), button.rect[1], button.rect[2], self[_level0_].BtnWidth, self[_level0_].BtnHeight)
							button.overlays[img] = ov
						else
							ov = button.overlays[img]
						end
						if button.enabled and not button.isHeader then
							safeOverlaySetColor(ov, 0.35, 0.65, 0.10, 1)
						else
							safeOverlaySetColor(ov, 1, 1, 1, button.isHeader and 1 or 0.55)
						end
						safeOverlayRender(ov)
					elseif button.enabled then
						if button.isHeader then
							safeOverlaySetColor(button.ovEnabled, 1, 1, 1, 1)
						else
							safeOverlaySetColor(button.ovEnabled, 0.35, 0.65, 0.10, 1)
						end
						safeOverlayRender(button.ovEnabled)
					else
						safeOverlaySetColor(button.ovDisabled, 1, 1, 1, 0.55)
						safeOverlayRender(button.ovDisabled)
					end
				end
			end
		end

		------------------------------------------------------------------------
		-- showGui
		------------------------------------------------------------------------
		function _newClass_:showGui(on)
			local old = false
			if self[_level0_] ~= nil then
				old = self[_level0_].GuiActive
			end
			if self.isClient then
				self[_level0_].GuiActive = on
			else
				self[_level0_].GuiActive = false
			end
			if old ~= self[_level0_].GuiActive and g_inputBinding ~= nil and g_inputBinding.setShowMouseCursor ~= nil then
				pcall(g_inputBinding.setShowMouseCursor, g_inputBinding, on)
			end
		end

		------------------------------------------------------------------------
		-- draw
		------------------------------------------------------------------------
		function _newClass_:draw(hideKey, alwaysDrawTitle)
			if self.isClient and self[_level0_] ~= nil then
				local titlePosY
				local showTitle
				if self[_level0_].GuiActive then
					if g_inputBinding ~= nil and g_inputBinding.setShowMouseCursor ~= nil then
						pcall(g_inputBinding.setShowMouseCursor, g_inputBinding, true)
					end
					titlePosY = self[_level0_].BtnPosY + self[_level0_].Border + self[_level0_].BtnHeight
					showTitle = true
				else
					titlePosY = self[_level0_].TextPosY
					showTitle = alwaysDrawTitle
				end

				setTextAlignment(RenderText ~= nil and RenderText.ALIGN_LEFT or 0)
				if self[_level0_].GuiActive then
					safeOverlayRender(self[_level0_].Overlay)
					safeOverlayRender(self[_level0_].Accent)
				end
				if showTitle then
					setTextBold(true)
					setTextColor(1, 1, 1, 1)

					renderText(self[_level0_].TextPosX, titlePosY, self[_level0_].TextSize, tostring(self[_level0_].Title or ""))
				end

				setTextBold(false)
				setTextColor(1, 1, 1, 1)

				if self[_level0_].GuiActive then
					local dynamic=self[_level0_].DynamicTooltip
					if dynamic~=nil and dynamic.textcb~=nil then
						self[_level0_].Tooltip=dynamic.textcb(self,_newClass_.getText(dynamic.text1))
					end
					if self[_level0_].Tooltip ~= nil and self[_level0_].Tooltip ~= "" then
						renderText(self[_level0_].TextPosX, self[_level0_].TextPosY, self[_level0_].TextSize, tostring(self[_level0_].Tooltip))
					elseif self[_level0_].InfoText ~= nil and self[_level0_].InfoText ~= "" then
						renderText(self[_level0_].TextPosX, self[_level0_].TextPosY, self[_level0_].TextSize, tostring(self[_level0_].InfoText))
					end
					_newClass_.renderButtons(self)
				end
			end
		end

		------------------------------------------------------------------------
		-- delete
		------------------------------------------------------------------------
		function _newClass_:delete()
			if self[_level0_] ~= nil and self[_level0_].Buttons ~= nil then
				for _, button in pairs(self[_level0_].Buttons) do
					if button.overlays ~= nil then
						for _, overlay in pairs(button.overlays) do
							safeOverlayDelete(overlay)
						end
					end
				end
				self[_level0_].Buttons = nil
			end
			if self[_level0_] ~= nil then
				safeOverlayDelete(self[_level0_].Overlay)
				safeOverlayDelete(self[_level0_].Accent)
			end
			self[_level0_] = nil
		end

		------------------------------------------------------------------------
		-- onLeave
		------------------------------------------------------------------------
		function _newClass_:onLeave()
			if self.isClient and self[_level0_] ~= nil and self[_level0_].GuiActive then
				if g_inputBinding ~= nil and g_inputBinding.setShowMouseCursor ~= nil then
					pcall(g_inputBinding.setShowMouseCursor, g_inputBinding, false)
				end
			end
		end

		------------------------------------------------------------------------
		-- onEnter
		------------------------------------------------------------------------
		function _newClass_:onEnter()
			if self[_level0_] ~= nil then
				_newClass_.showGui(self, self[_level0_].GuiActive)
				if self.isClient and self[_level0_].GuiActive and g_inputBinding ~= nil and g_inputBinding.setShowMouseCursor ~= nil then
					pcall(g_inputBinding.setShowMouseCursor, g_inputBinding, true)
				end
			end
		end

		_G[_globalClassName_] = _newClass_
	end

	_G[mogliHudClass].newClass = newClass
end
